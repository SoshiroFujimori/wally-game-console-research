def register(f, x, y, w, h, title, clock):
    f.box(x, y, w, h, title, fill=LIGHT, size=27)
    # Clock enters below the data input; the triangle denotes edge-triggered storage.
    f.poly([(x, y+h-26), (x+13, y+h-18), (x, y+h-10)])
    f.line([(x-24, y+h-18), (x, y+h-18)], arrow=False)
    f.text(x-36, y+h+7, w+44, 30, clock, 22)


